#!/usr/bin/env node
"use strict";

// Usage: node scripts/migrate-attendance-to-sqlite.js
// This script scans the .data directory for per-org attendance.json files
// and emits a SQL file at .data/attendance_migration.sql that can be
// imported into a SQLite database (e.g. `sqlite3 .data/attendance.db < .data/attendance_migration.sql`).

const fs = require('fs');
const path = require('path');

async function main() {
  const root = path.resolve(process.cwd(), '.data');
  try {
    await fs.promises.mkdir(root, { recursive: true });
  } catch (e) {
    // ignore
  }

  const outPath = path.join(root, 'attendance_migration.sql');
  const header = `-- SQLite import generated by scripts/migrate-attendance-to-sqlite.js
PRAGMA foreign_keys = OFF;
BEGIN TRANSACTION;

CREATE TABLE IF NOT EXISTS attendance (
  id TEXT PRIMARY KEY,
  orgId TEXT,
  memberName TEXT,
  username TEXT,
  qrCode TEXT,
  entryTime TEXT,
  exitTime TEXT,
  status TEXT,
  date TEXT,
  createdAt TEXT,
  syncStatus TEXT,
  lastSyncedAt TEXT,
  syncResult TEXT,
  serverReceivedAt TEXT
);

`;

  let sql = header;

  // find subdirectories under .data or attendance.json at root
  const entries = await fs.promises.readdir(root, { withFileTypes: true }).catch(() => []);
  const candidates = [];

  // root attendance.json
  const rootFile = path.join(root, 'attendance.json');
  if (fs.existsSync(rootFile)) candidates.push({ org: 'default', file: rootFile });

  for (const entry of entries) {
    if (entry.isDirectory()) {
      const orgDir = path.join(root, entry.name);
      const f = path.join(orgDir, 'attendance.json');
      if (fs.existsSync(f)) candidates.push({ org: entry.name, file: f });
    }
  }

  if (candidates.length === 0) {
    console.log('No attendance.json files found under .data. Nothing to migrate.');
    return;
  }

  for (const c of candidates) {
    try {
      const raw = await fs.promises.readFile(c.file, 'utf8');
      const parsed = JSON.parse(raw);
      if (!Array.isArray(parsed)) continue;
      for (const r of parsed) {
        const id = String(r.id || '');
        const escape = (v) => v === null || v === undefined ? '' : String(v).replace(/'/g, "''");
        const values = [
          id,
          c.org,
          escape(r.memberName),
          escape(r.username),
          escape(r.qrCode),
          escape(r.entryTime),
          escape(r.exitTime),
          escape(r.status),
          escape(r.date),
          escape(r.createdAt),
          escape(r.syncStatus),
          escape(r.lastSyncedAt),
          escape(r.syncResult),
          escape(r.serverReceivedAt),
        ].map((v) => `'${v}'`).join(',');

        sql += `INSERT OR IGNORE INTO attendance (id, orgId, memberName, username, qrCode, entryTime, exitTime, status, date, createdAt, syncStatus, lastSyncedAt, syncResult, serverReceivedAt) VALUES (${values});\n`;
      }
    } catch (e) {
      console.error('Failed to process', c.file, e.message || e);
    }
  }

  sql += '\nCOMMIT;\n';

  await fs.promises.writeFile(outPath, sql, 'utf8');
  console.log('Migration SQL written to', outPath);
  console.log('To import into SQLite:');
  console.log('  sqlite3 .data/attendance.db < .data/attendance_migration.sql');
  console.log('Or open the SQL file in your SQLite client and run it.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
